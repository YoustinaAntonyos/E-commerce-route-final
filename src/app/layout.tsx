import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import type { ReactNode } from "react";
import "./../styles/globals.css";
import Providers from "@/shared/components/Providers/Providers";
import { Toaster } from "sonner";
import Navbar from "@/shared/components/Layout/Navbar";
import Footer from "@/shared/components/Layout/Footer";
import { verifyTooken } from "@/features/auth/services/auth.action";
import { authReducer } from "@/features/auth/slices/auth.slice";
import { getCartItems } from "@/features/card/server/card.action";
import { CartValuesTypes } from "@/features/card/slices/cart.slice";
import { getWishlistItems } from "@/features/wishlist/server/wishlist.action";
import { wishlistInitialValues } from "@/features/wishlist/slices/wishlist.slice";
import { WishlistState } from "@/features/wishlist/types/wishlist.type";
import { getAllCategories } from "@/features/categories/services/getAllCategories";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }:LayoutProps<"/">)
  //  { children: ReactNode }) 
   {

  const authState = await verifyTooken()
  const categoriesResponse = await getAllCategories()

  let cartValues:CartValuesTypes ={
    cartId: null,
    status: "",
    numOfCartItems: 0,
    message: "",
    data: {
      products: [],
      totalCartPrice: 0
    }
  };

  let wishlistValues: WishlistState = { ...wishlistInitialValues, data: [] };

  if(authState.isAuthenticated === true){
     const cartResponse = await getCartItems()
     if(cartResponse.status === 'success'){
      cartValues = cartResponse
     }

     const wishlistResponse = await getWishlistItems()
     if(wishlistResponse.status === 'success'){
      wishlistValues = {
        status: wishlistResponse.status,
        message: wishlistResponse.message || "",
        data: wishlistResponse.data,
      }
     } else {
      wishlistValues = {
        status: wishlistResponse.status,
        message: wishlistResponse.message,
        data: [],
      }
     }
  }

  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <Providers preloadedState={{authReducer: authState, cartReducer: cartValues, wishlistReducer: wishlistValues}}>
          <Navbar
            categories={categoriesResponse.data}
            categoriesError={categoriesResponse.error}
          />
          {children}
          <Footer categories={categoriesResponse.data} />
          <Toaster richColors position="top-right" />
        </Providers>
      </body>
    </html>
  );
}
